package batalha.enums;

/**
 * Representa os tipos de terreno disponíveis durante uma batalha.
 *
 * <p>O tipo de terreno pode ser utilizado pelo sistema para identificar
 * o ambiente em que a batalha está acontecendo.</p>
 */
public enum TipoTerreno {
  ASFALTO_QUENTE,
  PISO_ESCORREGADIO,
  CANTEIRO_CENTRAL
}